/** 열 자산의 `rowId` 를 싣는 쿼리 파라미터. */
export const ASSET_EDIT_PARAM = "edit";

/** 이 자산의 수정 폼이 열린 채로 설정의 계좌·카드 관리를 여는 경로. */
export const editAssetPath = (assetRowId: number): string =>
  `/desk/settings?section=accounts&${ASSET_EDIT_PARAM}=${assetRowId}`;
